// 문제 1. 센서 보드 둘레와 넓이
// 예시 입력: 3 4  |  1000000000 1000000000  |  1 1000000000
// 예시 출력: 14 / 12 (각각 한 줄)  |  4000000000 / 1000000000000000000  |  2000000002 / 1000000000
// 걸린 시간:
// 힌트 사용: 안 봄 / 힌트1 / 힌트2
// AI 사용: 안 씀 / 풀고 나서 리뷰만 / 풀이 중에 씀
// 막힌 점:

#include <iostream>
using namespace std;

int main() {
    long long  w = 0;
    long long h = 0;
    cin >> w >>  h ;
    cout << "둘레 = " <<  (w + h) * 2 << '\n';
    cout << "넓이 = " << w * h << '\n';
    return 0;
}

